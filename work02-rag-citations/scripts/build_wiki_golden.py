def main() -> int:
    files = {int(p.name.split("_")[1]): p for p in CORPUS.glob("wiki_*.md")}
    out, bad = [], []
    for n, (q, snippet) in sorted(ANSWERABLE.items()):
        p = files.get(n)
        if p is None:
            bad.append((n, "article missing"))
            continue
        if snippet.lower() not in p.read_text(encoding="utf-8").lower():
            bad.append((n, f"snippet not in article: {snippet!r}"))
            continue
        out.append({"id": f"w{n:03d}", "question": q, "answerable": True, "doc_id": p.stem, "answer_snippet": snippet})
    for i, (q, kind) in enumerate(UNANSWERABLE, 1):
        out.append({"id": f"u{i:02d}", "question": q, "answerable": False, "kind": kind})
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wrote {len(out)} questions ({sum(x['answerable'] for x in out)} answerable); problems: {bad or 'none'}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
